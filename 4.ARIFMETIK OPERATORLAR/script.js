    //Arifmetik operatorlar nma uchun kerak?
//Bular bizga hisob-kitob amallarini bajarish uchun kerak boladi
//(+ - * / % * **)

// (+)Example:

let apple = 2000
let cherry = 3000

let totalPrice = apple + cherry   //=5000
console.log("Haridingiz shu narx : ", totalPrice);

// (-)Example:

let balance = 100
let withdraw = 30

let newBalance = balance - withdraw
console.log("Qolgan summa : " + newBalance);

//(*)Example:

let pen = 200
let skidka = 3

let narxJami = pen * skidka
console.log("Xaridingiz : " + narxJami);

//(/)Example:

let kitob = 24
let daftar = 4

let boluvSon = kitob / daftar
console.log( "kitob va daftar : "  + boluvSon);

//(%)Example

let oylik = 100
let ustama = 40

let jamiOylik = oylik % ustama
console.log("Jami oyligingiz : " + jamiOylik);

//(*) Example

let level = 2
level --;

console.log("score : " + level);


